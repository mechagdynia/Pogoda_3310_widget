/**
 * NOKIA 3310 WEATHER RETRO — procedural 5x7 bitmap font.
 *
 * A classic 5-pixel-wide monospace LCD font, fully self-contained (no
 * TTF/base64 payload needed — the "font" is data, which is exactly what
 * a 1-bit LCD wants). Includes full Polish diacritics:
 *   ogonek:  Ą Ę Ń      acute:  Ć Ó Ś Ź     dot-above:  Ż     slash:  Ł
 *
 * Diacritic glyphs are 5x8 with a `top` offset so the letter body stays
 * baseline-aligned with the 5x7 glyphs (mark above -> top=1,
 * ogonek/slash below -> top=0).
 */

export const FONT_W = 5;
export const FONT_H = 7;
/** Horizontal spacing in virtual px at scale 1. */
export const FONT_SPACING = 1;

export interface Glyph {
  /** One bitmask per row, MSB = leftmost pixel (5 bits). */
  rows: Uint8Array;
  /** 7 for base glyphs, 8 for diacritic glyphs. */
  h: number;
  /** Rows to subtract from the draw y so the letter body aligns. */
  top: number;
}

