/** Marks drawn ABOVE the baseline row get top = 1. */
const TOP_OFFSETS: ReadonlySet<string> = new Set([
  'Ć',
  'Ó',
  'Ś',
  'Ź',
  'Ż'
]);

/* ------------------------------------------------------------------ *
 *  Build the runtime glyph table (bitmask rows)
 * ------------------------------------------------------------------ */

function buildGlyph(key: string, rows: readonly string[]): Glyph {
  const h = rows.length;
  const bits = new Uint8Array(h);
  for (let y = 0; y < h; y++) {
    let v = 0;
    const row = rows[y];
    for (let x = 0; x < FONT_W; x++) {
      if (row.charCodeAt(x) === 35) v |= 1 << (FONT_W - 1 - x);
    }
    bits[y] = v;
  }
  return { rows: bits, h, top: TOP_OFFSETS.has(key) ? 1 : 0 };
}

const TABLE: ReadonlyMap<string, Glyph> = (() => {
  const m = new Map<string, Glyph>();
  for (const [key, rows] of Object.entries(G)) {
    m.set(key, buildGlyph(key, rows));
  }
  return m;
})();

const UNKNOWN = TABLE.get('?')!;

/**
 * Resolve a character to a glyph. Lowercase maps to uppercase (Nokia
 * style). Unknown characters render as '?'.
 */
export function glyphFor(ch: string): Glyph {
  if (ch.length !== 1) return UNKNOWN;
  const up = ch.toUpperCase();
  return TABLE.get(up) ?? UNKNOWN;
}

/** Advance width in virtual px for one character at a given scale. */
export function charAdvance(scale = 1): number {
  return (FONT_W + FONT_SPACING) * scale;
}

/** Total width in virtual px of a string at a given scale. */
export function textWidth(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return text.length * charAdvance(scale) - FONT_SPACING * scale;
}
